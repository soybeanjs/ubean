import { mkdir, readFile, writeFile } from 'node:fs/promises';
import type { ScanResult, ScannedLocale } from '@ubean/scan';
import { join } from 'pathe';

export interface I18nTypesOptions {
  outDir: string;
  fileName?: string;
  defaultLocale?: string;
}

function isIdent(key: string): boolean {
  return /^[A-Za-z_$][\w$]*$/.test(key);
}

/** Convert a JSON message tree into a TypeScript object type body. */
export function messagesToTsType(value: unknown, indent = 1): string {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    return 'string';
  }
  const obj = value as Record<string, unknown>;
  const keys = Object.keys(obj);
  if (keys.length === 0) return 'Record<string, never>';
  const pad = '  '.repeat(indent);
  const inner = keys
    .map(k => {
      const key = isIdent(k) ? k : JSON.stringify(k);
      return `${pad}${key}: ${messagesToTsType(obj[k], indent + 1)};`;
    })
    .join('\n');
  return `{\n${inner}\n${'  '.repeat(indent - 1)}}`;
}

function unwrapMessages(raw: unknown): Record<string, unknown> | null {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  const obj = raw as Record<string, unknown>;
  const hasMeta =
    typeof obj.name === 'string' || obj.dir === 'ltr' || obj.dir === 'rtl' || typeof obj.isDefault === 'boolean';
  if (hasMeta && obj.messages && typeof obj.messages === 'object' && obj.messages !== null) {
    return obj.messages as Record<string, unknown>;
  }
  return obj;
}

function pickDefaultLocaleFile(locales: ScannedLocale[], defaultLocale?: string): ScannedLocale | undefined {
  const jsonFiles = locales.filter(l => {
    const lower = l.fullPath.toLowerCase();
    return (lower.endsWith('.json') || lower.endsWith('.json5')) && !l.namespace;
  });
  if (jsonFiles.length === 0) return undefined;
  if (defaultLocale) {
    const match = jsonFiles.find(l => l.code === defaultLocale);
    if (match) return match;
  }
  return jsonFiles.find(l => l.isDefault) || jsonFiles[0];
}

/**
 * Locale codes scanned from `src/locales/` → vue-i18n `GeneratedTypeConfig`.
 *
 * `@intlify/core-base` derives `Locale = GeneratedLocale` from this interface
 * (`core-base.d.ts`: `Locale = IsNever<GeneratedLocale> extends true ? string : GeneratedLocale`),
 * so every `Composer.locale` / `createI18n({ locale })` surface narrows to the
 * union. Requires the leading `export {}` in the emitted file — without it the
 * `declare module` is not a module augmentation and silently does nothing.
 */
function localeUnionType(locales: ScannedLocale[]): string | null {
  const codes = [...new Set(locales.map(l => l.code))];
  if (codes.length === 0) return null;
  return codes.map(c => JSON.stringify(c)).join(' | ');
}

/**
 * Generate `.ubean/i18n.d.ts` augmenting vue-i18n `DefineLocaleMessage` from
 * the default locale JSON, plus `GeneratedTypeConfig['locale']` from the
 * scanned locale codes. The two halves are independent: message keys need a
 * JSON source, the locale union only needs the locale files to exist.
 */
export async function generateI18nTypes(result: ScanResult, options: I18nTypesOptions): Promise<string | null> {
  const { outDir, fileName = 'i18n.d.ts', defaultLocale } = options;
  const locales = result.locales || [];
  const localeUnion = localeUnionType(locales);

  const source = pickDefaultLocaleFile(locales, defaultLocale);
  let messages: Record<string, unknown> | null = null;
  if (source) {
    try {
      const text = await readFile(source.fullPath, 'utf8');
      messages = unwrapMessages(JSON.parse(text));
    } catch {
      // Unparsable locale JSON degrades to "locale union only" below — the
      // union does not depend on the message tree.
      messages = null;
    }
  }

  if (!messages && !localeUnion) return null;

  const origin = source ? `from ${source.relativePath}` : 'from scanned locale codes';
  const header = `// Auto-generated by ubean ${origin} — do not edit manually
// Typed \`t('key')\` via vue-i18n \`DefineLocaleMessage\` and \`Locale\` via
// \`@intlify/core-base\` \`GeneratedTypeConfig\`.
// Override by adding your own \`declare module\` in src/.
/* eslint-disable */
export {};
`;
  const messageBlock = messages
    ? `
declare module 'vue-i18n' {
  export interface DefineLocaleMessage ${messagesToTsType(messages, 2)}
}
`
    : '';
  const localeBlock = localeUnion
    ? `
declare module '@intlify/core-base' {
  export interface GeneratedTypeConfig {
    locale: ${localeUnion};
  }
}
`
    : '';
  const contents = `${header}${messageBlock}${localeBlock}`;

  await mkdir(outDir, { recursive: true });
  const outPath = join(outDir, fileName);
  await writeFile(outPath, contents, 'utf8');
  return outPath;
}
