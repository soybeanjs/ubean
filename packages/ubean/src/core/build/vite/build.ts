import { build as viteBuild } from 'vite';
import vue from '@vitejs/plugin-vue';
import { join, resolve, relative } from 'pathe';
import { mkdir, writeFile, rm, cp, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import type { ResolvedConfig } from '../../config/types';
import type { ScanResult } from '../../routing/types';
import { ubeanPlugin } from './plugin';
import { ubeanVuePlugin } from '../../vue/plugin';
import { ubeanIslandsPlugin } from '../../islands';
import { resolveModules } from '../../modules';
import type { Preset } from '../../preset/_utils/preset';
import { logger } from '../../log';
import {
  createRoutingVirtualModule,
  createPagesVirtualModule,
  createMetaVirtualModule,
  createAppVirtualModule,
  createLocalesVirtualModule
} from '../virtual/modules';
import { useVirtualRegistry } from '../virtual/registry';

export interface BuildOptions {
  cwd: string;
  config: ResolvedConfig;
  preset: Preset;
  scanResult: ScanResult;
  minify?: boolean;
  sourcemap?: boolean;
}

export interface BuildManifest {
  assets: Array<{
    file: string;
    src?: string;
    isEntry?: boolean;
    css?: string[];
  }>;
  entry: string;
  clientDir: string;
  serverDir: string;
  preset: string;
}

function getOutDirs(cwd: string, outputDir: string) {
  const outputRoot = resolve(cwd, outputDir);
  return {
    root: outputRoot,
    public: join(outputRoot, 'public'),
    server: join(outputRoot, 'server'),
    assets: join(outputRoot, 'public', 'assets'),
    virtual: join(cwd, '.ubean', 'virtual')
  };
}

async function generateVirtualModulesToDisk(
  cwd: string,
  config: ResolvedConfig,
  scanResult: ScanResult,
  virtualDir: string
) {
  await mkdir(virtualDir, { recursive: true });
  const registry = useVirtualRegistry();
  registry.clear();

  registry.register(
    createRoutingVirtualModule(
      scanResult.apiRoutes.map(r => ({
        method: r.method?.toUpperCase() || 'ALL',
        path: r.route,
        id: `${r.method}:${r.route}`,
        filePath: r.fullPath
      })),
      scanResult.middlewares.map(m => ({
        path: '/**',
        filePath: m.fullPath,
        order: m.order,
        global: m.global
      }))
    )
  );

  registry.register(
    createPagesVirtualModule(
      scanResult.pages.map(p => ({
        name: p.name,
        path: p.route,
        filePath: p.fullPath,
        layout: p.layout,
        reuseTarget: p.reuseTarget
      })),
      scanResult.layouts.map(l => ({
        name: l.name,
        filePath: l.fullPath,
        isDefault: l.isDefault
      }))
    )
  );

  registry.register(createMetaVirtualModule());

  registry.register(
    createAppVirtualModule(scanResult.apiRoutes, scanResult.middlewares, scanResult.pages, config.srcDir)
  );

  registry.register(createLocalesVirtualModule(scanResult.locales, scanResult.defaultLocale));

  const srcDir = resolve(cwd, config.srcDir);
  const pagesGlob = JSON.stringify(join(srcDir, 'pages/**/*.{vue,ts,tsx,js,jsx,md,mdx}').replace(/\\/g, '/'));
  const routesGlob = JSON.stringify(join(srcDir, 'routes/**/*.{ts,js,mjs}').replace(/\\/g, '/'));
  const middlewareGlob = JSON.stringify(join(srcDir, 'middleware/**/*.{ts,js,mjs}').replace(/\\/g, '/'));
  const appVuePath = join(srcDir, 'app.vue').replace(/\\/g, '/');

  const pagesMod = registry.getModules().find(m => m.id === 'ubean:pages');
  const pagesContent = `// Auto-generated by ubean
${pagesMod ? await pagesMod.load() : ''}
`;
  await writeFile(join(virtualDir, 'pages.mjs'), pagesContent, 'utf-8');

  const routesMod = registry.getModules().find(m => m.id === 'ubean:routes');
  const routesContent = `// Auto-generated by ubean
${routesMod ? await routesMod.load() : ''}
`;
  await writeFile(join(virtualDir, 'routes.mjs'), routesContent, 'utf-8');

  const appMod = registry.getModules().find(m => m.id === 'ubean:app-config');
  const appConfigContent = appMod ? await appMod.load() : '';
  await writeFile(join(virtualDir, 'app.mjs'), appConfigContent, 'utf-8');

  const localesMod = registry.getModules().find(m => m.id === 'ubean:locales');
  const localesContent = localesMod ? await localesMod.load() : '';
  await writeFile(join(virtualDir, 'locales.mjs'), localesContent, 'utf-8');

  const clientEntry = `// Auto-generated client entry
import { createApp } from 'vue';
import App from '${appVuePath}';
import { loadLocales } from 'ubean:locales';
import 'ubean/runtime/vue';

async function bootstrap() {
  await loadLocales();

  const app = createApp(App);
  
  if (typeof window !== 'undefined') {
    const el = document.getElementById('app');
    if (el) {
      app.mount(el);
    }
  }
}

bootstrap();
`;
  await writeFile(join(virtualDir, 'client-entry.mjs'), clientEntry, 'utf-8');

  const metaMod = registry.getModules().find(m => m.id === 'ubean:meta');
  const metaContent = metaMod ? await metaMod.load() : '';
  await writeFile(join(virtualDir, 'meta.mjs'), metaContent, 'utf-8');

  const serverEntry = `// Auto-generated server entry
import { createUbeanApp } from 'ubean/runtime/app';

export { createUbeanApp };

const routeModules = import.meta.glob(${routesGlob}, { eager: false });
const middlewareModules = import.meta.glob(${middlewareGlob}, { eager: false });
const pageModules = import.meta.glob(${pagesGlob}, { eager: false });

function normalizeKey(p) {
  return p.replace(/^.*src\\/(routes|middleware|pages)\\//, '');
}

export const routeLoaders = {};
for (const [key, loader] of Object.entries(routeModules)) {
  routeLoaders[normalizeKey(key)] = loader;
}

export const middlewareLoaders = {};
for (const [key, loader] of Object.entries(middlewareModules)) {
  middlewareLoaders[normalizeKey(key)] = loader;
}

export const pageLoaders = {};
for (const [key, loader] of Object.entries(pageModules)) {
  pageLoaders[normalizeKey(key)] = loader;
}

export async function createApp(options = {}) {
  const app = createUbeanApp({
    rootDir: ${JSON.stringify(cwd)},
    routeLoaders,
    middlewareLoaders,
    pageLoaders,
    publicDir: ${JSON.stringify(join(cwd, 'public').replace(/\\/g, '/'))},
    ...options
  });

  await app.init();
  return app;
}

export default async function createFetchHandler() {
  const app = await createApp();
  return app.fetch;
}

export const handler = async (req, ctx) => {
  const app = await createApp();
  return app.fetch(req, ctx);
};
`;
  await writeFile(join(virtualDir, 'server-entry.mjs'), serverEntry, 'utf-8');

  return virtualDir;
}

function getPresetBuildConfig(preset: Preset) {
  const presetName = preset.name;

  switch (presetName) {
    case 'node':
    case 'bun':
    case 'deno':
      return {
        format: 'esm' as const,
        target: 'node18',
        entryType: 'node' as const,
        external: [
          'hono',
          'vue',
          'vue/server-renderer',
          /^ubean(\/.*)?$/,
          /^node:/
        ]
      };
    case 'cloudflare':
      return {
        format: 'esm' as const,
        target: 'es2022',
        entryType: 'worker' as const,
        external: ['hono', 'vue', 'vue/server-renderer', /^ubean(\/.*)?$/]
      };
    case 'standard':
    default:
      return {
        format: 'esm' as const,
        target: 'es2022',
        entryType: 'fetch' as const,
        external: ['hono', 'vue', 'vue/server-renderer', /^ubean(\/.*)?$/]
      };
  }
}

function generateNodeServerEntry(): string {
  return `// Auto-generated ubean Node.js server entry
import { serve } from 'hono/node-server';
import createFetchHandler from './entry.mjs';

const port = process.env.PORT || 3000;
const host = process.env.HOST || '0.0.0.0';

async function main() {
  const fetch = await createFetchHandler();
  console.log(\`Starting ubean server on http://\${host}:\${port}\`);
  serve({ fetch, port: Number(port), hostname: host });
}

main();
`.trim();
}

function generateStandardHandlerEntry(): string {
  return `// Auto-generated ubean standard fetch handler
import createFetchHandler from './entry.mjs';

const handlerPromise = createFetchHandler();
export default async function fetch(req, ctx) {
  const handler = await handlerPromise;
  return handler(req, ctx);
}
`.trim();
}

function generateCloudflareWorkerEntry(): string {
  return `// Auto-generated ubean Cloudflare Worker entry
import createFetchHandler from './entry.mjs';

const handlerPromise = createFetchHandler();
export default {
  async fetch(req, env, ctx) {
    const handler = await handlerPromise;
    return handler(req, { ...ctx, env });
  }
};
`.trim();
}

export async function buildProduction(options: BuildOptions): Promise<BuildManifest> {
  const { cwd, config, preset, scanResult, minify = true, sourcemap = false } = options;
  const outDirs = getOutDirs(cwd, config.build.outputDir);
  const srcDir = resolve(cwd, config.srcDir);

  logger.info('Cleaning output directory...');
  if (existsSync(outDirs.root)) {
    await rm(outDirs.root, { recursive: true, force: true });
  }
  await mkdir(outDirs.public, { recursive: true });
  await mkdir(outDirs.server, { recursive: true });

  logger.info('Generating virtual modules...');
  await generateVirtualModulesToDisk(cwd, config, scanResult, outDirs.virtual);

  const builtinPlugins: any[] = [
    vue(),
    ubeanPlugin({ config }),
    ...ubeanVuePlugin({ config }),
    ubeanIslandsPlugin()
  ];

  const { plugins } = await resolveModules({
    cwd,
    config,
    builtinPlugins
  });

  const presetBuildConfig = getPresetBuildConfig(preset);
  const virtualDir = outDirs.virtual;

  const commonResolve = {
    alias: {
      '#ubean-pages': join(virtualDir, 'pages.mjs'),
      '#ubean-app': join(virtualDir, 'app.mjs'),
      '#ubean-client-entry': join(virtualDir, 'client-entry.mjs'),
      'ubean:pages': join(virtualDir, 'pages.mjs'),
      'ubean:routes': join(virtualDir, 'routes.mjs'),
      'ubean:app-config': join(virtualDir, 'app.mjs'),
      'ubean:locales': join(virtualDir, 'locales.mjs'),
      'ubean:meta': join(virtualDir, 'meta.mjs')
    }
  };

  logger.info('Building client bundle...');
  const clientEntryPath = join(srcDir, 'entry.client.ts');
  const clientInput = existsSync(clientEntryPath)
    ? clientEntryPath
    : join(virtualDir, 'client-entry.mjs');

  await viteBuild({
    root: cwd,
    configFile: false,
    mode: 'production',
    build: {
      outDir: outDirs.public,
      assetsDir: 'assets',
      minify: minify ? 'esbuild' : false,
      sourcemap,
      manifest: true,
      ssrManifest: true,
      rollupOptions: {
        input: {
          app: clientInput
        },
        output: {
          entryFileNames: 'assets/[name]-[hash].js',
          chunkFileNames: 'assets/chunks/[name]-[hash].js',
          assetFileNames: 'assets/[name]-[hash].[ext]'
        }
      },
      emptyOutDir: false
    },
    plugins: [...plugins],
    resolve: commonResolve,
    optimizeDeps: {
      exclude: ['ubean', '#ubean-pages', '#ubean-app', '#ubean-client-entry']
    }
  });

  let clientManifest: Record<string, any> = {};
  const manifestPath = join(outDirs.public, '.vite', 'manifest.json');
  if (existsSync(manifestPath)) {
    try {
      clientManifest = JSON.parse(await readFile(manifestPath, 'utf-8'));
    } catch {}
  }

  const publicDir = join(cwd, 'public');
  if (existsSync(publicDir)) {
    logger.info('Copying public assets...');
    await cp(publicDir, outDirs.public, { recursive: true });
  }

  logger.info('Building SSR bundle...');
  const serverEntryPath = join(virtualDir, 'server-entry.mjs');

  await viteBuild({
    root: cwd,
    configFile: false,
    mode: 'production',
    ssr: {
      target: presetBuildConfig.target === 'node18' ? 'node' : 'webworker',
      noExternal: ['ubean']
    },
    build: {
      outDir: outDirs.server,
      ssr: true,
      minify: false,
      sourcemap,
      rollupOptions: {
        input: serverEntryPath,
        external: presetBuildConfig.external,
        output: {
          format: presetBuildConfig.format,
          entryFileNames: 'entry.mjs',
          chunkFileNames: 'chunks/[name]-[hash].mjs',
          inlineDynamicImports: presetBuildConfig.entryType === 'worker'
        }
      },
      emptyOutDir: false
    },
    plugins: [...plugins],
    resolve: commonResolve
  });

  let serverEntry = 'entry.mjs';

  if (presetBuildConfig.entryType === 'node') {
    await writeFile(join(outDirs.server, 'server.mjs'), generateNodeServerEntry(), 'utf-8');
    serverEntry = 'server.mjs';

    const pkgJson = {
      type: 'module',
      private: true,
      main: './server.mjs',
      dependencies: {
        hono: '^4.0.0'
      }
    };
    await writeFile(join(outDirs.server, 'package.json'), JSON.stringify(pkgJson, null, 2), 'utf-8');
  } else if (presetBuildConfig.entryType === 'worker') {
    await writeFile(join(outDirs.server, 'worker.mjs'), generateCloudflareWorkerEntry(), 'utf-8');
    serverEntry = 'worker.mjs';

    const wranglerToml = `
name = "ubean-app"
main = "./server/worker.mjs"
compatibility_date = "2024-01-01"
assets = { directory = "./public" }
`.trim();
    await writeFile(join(outDirs.root, 'wrangler.toml'), wranglerToml, 'utf-8');
  } else {
    await writeFile(join(outDirs.server, 'handler.mjs'), generateStandardHandlerEntry(), 'utf-8');
    serverEntry = 'handler.mjs';
  }

  const assets: BuildManifest['assets'] = [];
  for (const [key, value] of Object.entries(clientManifest)) {
    const entry = value as any;
    assets.push({
      file: entry.file,
      src: key,
      isEntry: entry.isEntry,
      css: entry.css
    });
  }

  const manifest: BuildManifest = {
    assets,
    entry: serverEntry,
    clientDir: relative(cwd, outDirs.public),
    serverDir: relative(cwd, outDirs.server),
    preset: preset.name || 'standard'
  };

  await writeFile(join(outDirs.root, 'manifest.json'), JSON.stringify(manifest, null, 2), 'utf-8');

  logger.success(`Build complete! Output: ${outDirs.root}`);
  logger.info(`  Client assets: ${outDirs.public}`);
  logger.info(`  Server bundle: ${outDirs.server}`);
  logger.info(`  Entry: ${serverEntry}`);

  return manifest;
}
