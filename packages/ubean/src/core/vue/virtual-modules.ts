import { defineVirtualModule } from '../build/virtual/registry';
import type { ScannedPageRoute, ScannedLayout } from '../routing/types';

export function createVuePagesVirtualModule(pages: ScannedPageRoute[], layouts: ScannedLayout[]) {
  return defineVirtualModule('#ubean-pages', () => {
    const pageEntries: string[] = [];
    for (const p of pages) {
      pageEntries.push(
        `  ${JSON.stringify(p.name)}: () => import(${JSON.stringify(`/src/pages/${p.relativePath}`)}).then(m => m.default || m)`
      );
    }

    const layoutEntries: string[] = [];
    for (const l of layouts) {
      layoutEntries.push(
        `  ${JSON.stringify(l.name)}: () => import(${JSON.stringify(`/src/layouts/${l.relativePath}`)}).then(m => m.default || m)`
      );
    }

    const defaultLayout = layouts.find(l => l.isDefault);

    const pageNames = pages.map(p => JSON.stringify(p.name)).join(' | ') || 'string';
    const layoutNames = layouts.map(l => JSON.stringify(l.name)).join(' | ') || 'string';

    return `${`
// Auto-generated by ubean - do not edit
/* eslint-disable */

const _pageLoaders = {
${pageEntries.join(',\n')}
};

const _layoutLoaders = {
${layoutEntries.join(',\n')}
};

export const pageNames = [${pages.map(p => JSON.stringify(p.name)).join(', ')}] as const;
export const layoutNames = [${layouts.map(l => JSON.stringify(l.name)).join(', ')}] as const;
export const defaultLayout = ${defaultLayout ? JSON.stringify(defaultLayout.name) : 'null'} as const;

export type RouteName = ${pageNames};
export type LayoutName = ${layoutNames};

export function resolvePageComponent(name: string): Promise<any> {
  const loader = _pageLoaders[name];
  if (!loader) {
    return Promise.reject(new Error('[ubean] Page component not found: ' + name));
  }
  return loader();
}

export function resolveLayoutComponent(name: string | false | null | undefined): Promise<any> {
  if (!name || name === false) return Promise.resolve(null);
  const loader = _layoutLoaders[name];
  if (!loader) {
    return Promise.reject(new Error('[ubean] Layout component not found: ' + name));
  }
  return loader();
}

export const pages = {
${pages.map(p => `  ${JSON.stringify(p.name)}: { name: ${JSON.stringify(p.name)}, route: ${JSON.stringify(p.route)}, path: ${JSON.stringify(p.path)}, layout: ${JSON.stringify(p.layout)} }`).join(',\n')}
};

export const layouts = {
${layouts.map(l => `  ${JSON.stringify(l.name)}: { name: ${JSON.stringify(l.name)}, isDefault: ${l.isDefault} }`).join(',\n')}
};

export default {
  pageNames,
  layoutNames,
  defaultLayout,
  resolvePageComponent,
  resolveLayoutComponent,
  pages,
  layouts
};
`.trim()}\n`;
  });
}

